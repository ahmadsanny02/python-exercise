# Program Pertukaran Nilai dengan Variable Bantu

a = int(input("Masukkan bilangan 1: "))
b = int(input("Masukkan bilangan 2: "))

print("--- Sebelum pertukaran nilai ---")
print(f"Bilangan 1: {a}")
print(f"Bilangan 2: {b}")

c = a
a = b
b = c

print("--- Setelah pertukaran nilai ---")
print(f"Bilangan 1: {a}")
print(f"Bilangan 2: {b}")


print("\n")

