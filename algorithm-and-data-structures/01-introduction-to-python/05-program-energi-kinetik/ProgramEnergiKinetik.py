# Program Energi Kinetik
massa = float(input("Masukkan massa benda (kg): "))
kecepatan = float(input("Masukkan kecepatan benda: "))

energiKinetik = 0.5 * massa * (kecepatan ** 2)

print(f"Energi kinetik adalah: {energiKinetik}")

